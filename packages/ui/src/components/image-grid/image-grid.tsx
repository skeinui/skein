import { useLayoutEffect, useRef } from "react";
import type { ComponentPropsWithoutRef, ReactNode } from "react";
import type { ImageGridRatio, ImageGridStatus } from "../../contract.ts";
import { Image } from "../image/index.ts";
import type { ImageLabels } from "../image/index.ts";
import { useLabels } from "../../locales/use-labels.ts";

type Without<T> = Omit<T, "className" | "style">;

export interface ImageGridItem {
  /** Unique id, stable while the item's status changes (used as its key). */
  id: string;
  /** Image name (for screen readers, also the name in the preview). */
  alt: string;
  /** loading: generating / loading; ready: ready (src given); error: failed. Default ready. */
  status?: ImageGridStatus;
  /** Image address when ready. */
  src?: string;
  /** Address of the large image for preview, uses src if omitted. */
  previewSrc?: string;
  /** Progress while loading (0–100): if given a progress bar is shown, otherwise only the placeholder animation. */
  progress?: number;
  /** Reason shown on failure. */
  error?: string;
}

export interface ImageGridLabels {
  /** Text while loading, default `Generating image ${n}` (n counts from 1). */
  loading?: (index: number, alt: string) => string;
  /** Title on failure, default "Failed to load".  */
  failed?: string;
  /** Retry button, default "Retry". */
  retry?: string;
  /** Name of the remove button, default `Remove ${alt}`. */
  remove?: (alt: string) => string;
  /** Name of the progress bar, default "Progress". */
  progress?: string;
}

export interface ImageGridProps extends Without<ComponentPropsWithoutRef<"ul">> {
  /** The images (`ImageGridItem`: `id`, `alt`, `status`, `src`, `progress`), in display order. */
  items: readonly ImageGridItem[];
  /** Number of columns; if omitted it is automatic by count: 1 image 1 column, 2 to 4 images 2 columns, 5 to 9 images 3 columns, more 4 columns. */
  columns?: 1 | 2 | 3 | 4;
  /**
   * Aspect ratio of each cell (1:1 / 4:3 / 3:4 / 16:9), the same for every cell.
   * @default "square"
   */
  ratio?: ImageGridRatio;
  /** A "Retry" button appears in failed cells. */
  onRetry?: (item: ImageGridItem) => void;
  /** A remove button appears in the top right of each cell. */
  onRemove?: (item: ImageGridItem) => void;
  /** Actions that appear at the bottom of a ready cell on hover (or keyboard focus); write buttons with `ImageGrid.Action`. */
  actions?: (item: ImageGridItem) => ReactNode;
  /** Preview-related text, same as `Image`. */
  previewLabels?: Partial<ImageLabels>;
  labels?: ImageGridLabels;
}

/** Fill of the progress bar: the width is a runtime number, written as a CSS variable, and the theme style decides how to draw it. */
function ProgressFill({ value }: { value: number }) {
  const el = useRef<HTMLSpanElement>(null);
  useLayoutEffect(() => {
    el.current?.style.setProperty("--grid-progress", `${Math.min(100, Math.max(0, value))}%`);
  }, [value]);
  return <span ref={el} data-slot="image-grid-progress-bar" />;
}

const autoColumns = (n: number): 1 | 2 | 3 | 4 => (n <= 1 ? 1 : n <= 4 ? 2 : n <= 9 ? 3 : 4);

const icon = (children: ReactNode) => (
  <svg
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    strokeWidth="2"
    strokeLinecap="round"
    strokeLinejoin="round"
    aria-hidden="true"
  >
    {children}
  </svg>
);

/**
 * Image grid with states: each cell is loading (placeholder + optional progress) / ready (an image, click to preview, switchable when grouped) / failed (reason + retry).
 * General purpose: usable for several images generated by AI at once, batch uploads and batch-processing results. Cells have an equal aspect ratio and the column count is automatic by count.
 * Loading cells are not announced by screen readers, and the whole group is `aria-busy`; ready images reuse `Image` (the whole image is a button, Enter opens the preview).
 */
function ImageGridRoot({
  items,
  columns,
  ratio = "square",
  onRetry,
  onRemove,
  actions,
  previewLabels,
  labels: labelsProp,
  ...rest
}: ImageGridProps) {
  const labels = useLabels("imageGrid", labelsProp);
  const busy = items.some((item) => (item.status ?? "ready") === "loading");
  return (
    <Image.PreviewGroup labels={previewLabels}>
      <ul
        {...rest}
        data-slot="image-grid"
        data-columns={columns ?? autoColumns(items.length)}
        data-ratio={ratio}
        aria-busy={busy || undefined}
      >
        {items.map((item, index) => {
          const status = item.status ?? "ready";
          const ready = status === "ready" && item.src !== undefined;
          return (
            <li key={item.id} data-slot="image-grid-item" data-status={ready ? "ready" : status}>
              {ready ? (
                <Image src={item.src!} alt={item.alt} previewSrc={item.previewSrc} />
              ) : status === "loading" ? (
                <div data-slot="image-grid-loading">
                  <span data-slot="image-grid-status">{labels.loading(index + 1, item.alt)}</span>
                  {item.progress !== undefined ? (
                    <div
                      data-slot="image-grid-progress"
                      role="progressbar"
                      aria-label={labels.progress}
                      aria-valuemin={0}
                      aria-valuemax={100}
                      aria-valuenow={Math.round(item.progress)}
                    >
                      <ProgressFill value={item.progress} />
                    </div>
                  ) : null}
                </div>
              ) : (
                <div data-slot="image-grid-error">
                  {icon(
                    <>
                      <circle cx="12" cy="12" r="10" />
                      <path d="M12 8v4M12 16h.01" />
                    </>,
                  )}
                  <span data-slot="image-grid-message">{item.error ?? labels.failed}</span>
                  {onRetry ? (
                    <button
                      type="button"
                      data-slot="image-grid-retry"
                      onClick={() => onRetry(item)}
                    >
                      {labels.retry}
                    </button>
                  ) : null}
                </div>
              )}
              {ready && actions ? <div data-slot="image-grid-actions">{actions(item)}</div> : null}
              {onRemove ? (
                <button
                  type="button"
                  data-slot="image-grid-remove"
                  aria-label={labels.remove(item.alt)}
                  onClick={() => onRemove(item)}
                >
                  {icon(<path d="M18 6 6 18M6 6l12 12" />)}
                </button>
              ) : null}
            </li>
          );
        })}
      </ul>
    </Image.PreviewGroup>
  );
}

export interface ImageGridActionProps extends Without<ComponentPropsWithoutRef<"button">> {
  /** Name of the button (icon only, required). */
  "aria-label": string;
}

/** Action button below a ready cell (download, regenerate, copy...): icon only, so the name is required. */
function ImageGridAction(props: ImageGridActionProps) {
  return <button type="button" {...props} data-slot="image-grid-action" />;
}

export const ImageGrid = Object.assign(ImageGridRoot, { Action: ImageGridAction });
