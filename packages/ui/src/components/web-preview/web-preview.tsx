import { useLayoutEffect, useRef, useState } from "react";
import { isSafeUrl } from "../markdown/url.ts";
import { useLabels } from "../../locales/use-labels.ts";

export interface WebPreviewLabels {
  /** Reload button, default "Reload". */
  reload?: string;
  /** Open in a new tab, default "Open in new tab". */
  open?: string;
  /** Address bar, default "Address". */
  address?: string;
  /** Screen reader text while loading, default "Loading". */
  loading?: string;
  /** Hint when the address is not http(s), default "Only http(s) addresses can be previewed". */
  invalid?: string;
  /** Name of the iframe when `title` is not given. */
  title?: string;
}

interface WebPreviewBase {
  /** Name of the iframe (for screen readers), default "Preview". */
  title?: string;
  /**
   * Height of the preview area (px), default 360.
   * @default 360
   */
  height?: number;
  /**
   * Sandbox of the iframe. Default `allow-scripts allow-forms`: scripts and forms can run, but it is cross-origin (cannot read the host's cookies / storage),
   * cannot open popups and cannot navigate the host. Giving `allow-scripts` + `allow-same-origin` is the same as having no sandbox, so add it only when the content is fully trusted.
   * @default "allow-scripts allow-forms"
   */
  sandbox?: string;
  /**
   * The address bar is editable, default true; read-only when false. Enter navigates (an address without a protocol gets `https://`;
   * anything but http(s), such as `javascript:` / `data:` / `file:`, is rejected), Esc restores the current address.
   * @default true
   */
  editable?: boolean;
  /** Triggered after the user navigates from the address bar. */
  onNavigate?: (url: string) => void;
  labels?: WebPreviewLabels;
}

export type WebPreviewProps =
  | (WebPreviewBase & {
      /** Address to load in the iframe (only http(s) is accepted); shown in the address bar. Pass either `src` or `html`. */
      src: string;
      html?: never;
    })
  | (WebPreviewBase & {
      /**
       * A complete HTML document rendered in the iframe via srcdoc (e.g. code generated by a model). Pass either `src` or `html`.
       * With `html` the toolbar shows the title instead of an address and has no open-in-new-tab link.
       */
      html: string;
      src?: never;
    });

const isHttp = (url: string) => /^https?:\/\//i.test(url.trim());

/** An address without a protocol is completed with https, others are returned as is; unsafe ones return null. */
function normalize(input: string): string | null {
  const raw = input.trim();
  if (raw === "") return null;
  const url = /^[a-z][a-z0-9+.-]*:/i.test(raw) ? raw : `https://${raw}`;
  return isHttp(url) && isSafeUrl(url) ? url : null;
}

const icon = (children: React.ReactNode) => (
  <svg
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    strokeWidth="2"
    strokeLinecap="round"
    strokeLinejoin="round"
    aria-hidden="true"
  >
    {children}
  </svg>
);

/**
 * Web preview: sandboxed iframe + address bar (Enter to navigate) + reload + open in a new tab.
 * Content can be an address (`src`, only http(s) is accepted) or a piece of HTML (`html`, using srcdoc). The iframe by default only enables scripts and forms and is cross-origin,
 * and while loading there is a screen-reader-readable status below the address bar. The browser's back / forward cannot get a cross-origin iframe's history, so they are not provided.
 */
export function WebPreview(props: WebPreviewProps) {
  const {
    title: titleProp,
    height = 360,
    sandbox = "allow-scripts allow-forms",
    labels: labelsProp,
  } = props;
  const labels = useLabels("webPreview", labelsProp);
  const title = titleProp ?? labels.title;
  const editable = props.editable ?? true;
  const incoming = props.src ?? "";
  const [url, setUrl] = useState(incoming);
  const [draft, setDraft] = useState(incoming);
  const [seen, setSeen] = useState(incoming);
  const [reloads, setReloads] = useState(0);
  const [loading, setLoading] = useState(true);
  const [invalid, setInvalid] = useState(false);
  const viewport = useRef<HTMLDivElement>(null);

  // src was changed from outside: the address bar and iframe follow
  if (incoming !== seen) {
    setSeen(incoming);
    setUrl(incoming);
    setDraft(incoming);
    setInvalid(false);
    setLoading(true);
  }

  useLayoutEffect(() => {
    viewport.current?.style.setProperty("--web-height", `${height}px`);
  }, [height]);

  const go = () => {
    const next = normalize(draft);
    if (!next) {
      setInvalid(true);
      return;
    }
    setInvalid(false);
    setDraft(next);
    if (next !== url) {
      setUrl(next);
      setLoading(true);
      props.onNavigate?.(next);
    } else reload();
  };
  const reload = () => {
    setLoading(true);
    setReloads((n) => n + 1);
  };

  const hasUrl = props.html === undefined;
  const openable = hasUrl && isHttp(url) && isSafeUrl(url);
  const errorId = "web-preview-error";

  return (
    <div data-slot="web-preview" data-loading={loading ? "" : undefined}>
      <div data-slot="web-preview-toolbar">
        <button
          type="button"
          data-slot="web-preview-action"
          aria-label={labels.reload}
          onClick={reload}
        >
          {icon(
            <>
              <path d="M21 12a9 9 0 1 1-3-6.7" />
              <path d="M21 3v6h-6" />
            </>,
          )}
        </button>
        {hasUrl ? (
          <input
            type="text"
            data-slot="web-preview-url"
            value={draft}
            readOnly={!editable}
            spellCheck={false}
            autoComplete="off"
            aria-label={labels.address}
            aria-invalid={invalid || undefined}
            aria-describedby={invalid ? errorId : undefined}
            onChange={(e) => {
              setDraft(e.target.value);
              setInvalid(false);
            }}
            onKeyDown={(e) => {
              if (e.key === "Enter" && editable) {
                e.preventDefault();
                go();
              }
              if (e.key === "Escape") {
                setDraft(url);
                setInvalid(false);
              }
            }}
          />
        ) : (
          <span data-slot="web-preview-url" data-static="">
            {title}
          </span>
        )}
        {openable ? (
          <a
            data-slot="web-preview-action"
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={labels.open}
          >
            {icon(
              <>
                <path d="M15 3h6v6" />
                <path d="M10 14 21 3" />
                <path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6" />
              </>,
            )}
          </a>
        ) : null}
      </div>
      {invalid ? (
        <div data-slot="web-preview-error" id={errorId} role="alert">
          {labels.invalid}
        </div>
      ) : null}
      <div ref={viewport} data-slot="web-preview-viewport">
        <iframe
          key={reloads}
          data-slot="web-preview-frame"
          title={title}
          sandbox={sandbox}
          referrerPolicy="no-referrer"
          loading="lazy"
          {...(hasUrl ? { src: url } : { srcDoc: props.html })}
          onLoad={() => setLoading(false)}
        />
        {loading ? (
          <div data-slot="web-preview-loading" role="status">
            {labels.loading}
          </div>
        ) : null}
      </div>
    </div>
  );
}
